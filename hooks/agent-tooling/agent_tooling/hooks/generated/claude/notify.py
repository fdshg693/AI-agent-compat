def _unsupported() -> dict:
    return {"ok": False, "mode": "unsupported", "detail": f"platform={sys.platform}"}


def notify_sound(sound_path: Path | None, *, enabled: bool = True) -> dict:
    """通知音を鳴らす。`sound_path` は再生するファイル（無ければ OS の既定音）。

    Windows は再生が終わるまで待つ（WAV のみ）。macOS は afplay を切り離して待たない。
    """
    backend = _SOUND_BACKENDS.get(sys.platform)
    if backend is None:
        return _unsupported()
    if not enabled:
        return {"ok": False, "mode": "disabled"}
    try:
        return backend(sound_path)
    except Exception as exc:
        return {"ok": False, "mode": "error", "detail": str(exc)}


def notify_popup(
    text: str,
    seconds: float,
    project: str,
    *,
    entry_script: Path,
    popup_flag: str,
    enabled: bool = True,
    subtitle: str = "",
    notification_id: str = "",
    helper_app: Path | None = None,
    session_id: str = "",
    state_dir: Path | None = None,
) -> dict:
    """視覚通知を出す（呼び出し元を長くブロックしない）。

    - Windows: `entry_script`（実行中のフック。インライン化後は `sys.argv[0]`）を
      `popup_flag text seconds project session_id state_dir` 付きの別プロセスで再実行する。
      子プロセス側は呼び出し元のエントリが argv を分岐して `run_notify_popup()` を呼ぶ。
      同じ `session_id` の古い窓は、`state_dir`（`notify_state_dir()`）に残した記録を
      使って閉じてから出す。`subtitle`・`notification_id`・`helper_app` は使わない
    - macOS: 通知センターへ同期で出す（タイトル=`project`、サブタイトル=`subtitle`、
      本文=`text` を整形したもの）。`notification_id` が同じ通知は置き換わる。
      `helper_app` は通知ヘルパー `<Name>.app`（`mac_helper_app()`）。
      `seconds`・`session_id`・`state_dir` は使わない
    """
    backend = _POPUP_SPAWNERS.get(sys.platform)
    if backend is None:
        return _unsupported()
    if not enabled:
        return {"ok": False, "mode": "disabled"}
    try:
        return backend(
            text,
            seconds,
            project,
            entry_script,
            popup_flag,
            subtitle=subtitle,
            notification_id=notification_id,
            helper_app=helper_app,
            session_id=session_id,
            state_dir=state_dir,
        )
    except Exception as exc:
        return {"ok": False, "mode": "spawn_failed", "detail": str(exc)}


def run_notify_popup(
    text: str,
    seconds: float,
    project: str,
    app_name: str,
    *,
    session_id: str = "",
    state_dir: Path | None = None,
) -> None:
    """`notify_popup()` が起動した子プロセスの本体。ウィンドウを閉じるまで戻らない。

    手で実行したときに見えるよう、窓の例外はそのまま出す（子プロセスの出力は捨てている）。
    """
    backend = _POPUP_WINDOWS.get(sys.platform)
    if backend is not None:
        backend(text, seconds, project, app_name, session_id=session_id, state_dir=state_dir)


def notify_state_dir(local_app_data: str | None) -> Path | None:
    """通知の状態ファイルを置く既定のディレクトリ（`<LOCALAPPDATA>/agent-tooling/notify`）。

    `local_app_data` は呼び出し元が環境変数から読んで渡す。空なら None（置き換え等をしない）。
    フックの配置先（プロジェクト・グローバル、Claude・Kilo）によらず 1 つで済ませる。
    """
    if not local_app_data or not local_app_data.strip():
        return None
    return Path(local_app_data.strip()) / "agent-tooling" / "notify"


def notify_suppression(state_dir: Path | None, session_id: str = "") -> dict:
    """今効いている抑止（ポップアップのボタンで選んだスヌーズ・消音）。

    戻り値は `{"snooze": {"scope": "global"|"session", "until": <epoch 秒>} | None,
    "mute": 同じ形 | None}`。スヌーズは音も窓も、消音は音だけを止める合図で、
    `notify_sound`／`notify_popup` の `enabled` への合成はアダプタが行う。
    抑止のボタンを持つ OS（`_POPUP_WINDOWS` にある OS＝Windows）だけで判定し、
    それ以外の OS・`state_dir` が無い・状態ファイルが読めないときは抑止なしを返す。
    """
    none = {"snooze": None, "mute": None}
    if sys.platform not in _POPUP_WINDOWS or state_dir is None:
        return none
    try:
        return _state_check(state_dir, session_id)
    except Exception:
        return none


def suppression_reason(suppression: dict) -> str:
    """`notify_suppression()` の結果をログ用の 1 語にする（例: `snooze:global,mute:session`）。

    抑止が無ければ空文字。
    """
    return ",".join(
        f"{kind}:{entry['scope']}"
        for kind in ("snooze", "mute")
        if (entry := suppression.get(kind))
    )


def notify_post(
    title: str,
    subtitle: str,
    body: str,
    *,
    sound: str = "",
    notification_id: str = "",
    helper_app: Path | None = None,
) -> dict:
    """identifier 付きの通知を出す（同期。上限付きで、呼び出し元を長くブロックしない）。

    `body` はここで整形する（`truncate_body()`）。`notification_id` が同じ通知は
    置き換わる（空なら置き換えの対象にしない）。`sound` は通知の音の名前（macOS は
    `Glass`・`Hero` などのシステムサウンド名。空なら音なし）。`helper_app` は通知ヘルパー
    `<Name>.app`（`mac_helper_app()`）。対応は macOS だけで、それ以外は `unsupported`。
    """
    backend = _POST_BACKENDS.get(sys.platform)
    if backend is None:
        return _unsupported()
    try:
        return backend(
            title,
            subtitle,
            truncate_body(body),
            sound=sound,
            notification_id=notification_id,
            helper_app=helper_app,
        )
    except Exception as exc:
        return {"ok": False, "mode": "error", "detail": str(exc)}


def notify_remove(
    notification_id: str,
    *,
    helper_app: Path | None = None,
    timeout: float | None = None,
) -> dict:
    """`notification_id` の通知を消す。`timeout` 秒（省略時は既定の上限）で打ち切る。

    id が空なら何もしない（`no_id`）。対応は macOS のヘルパー経由だけで、それ以外は
    `unsupported`。ヘルパーが無いと消せない（`helper_missing`）。
    """
    backend = _REMOVE_BACKENDS.get(sys.platform)
    if backend is None:
        return _unsupported()
    try:
        if timeout is None:
            return backend(notification_id, helper_app=helper_app)
        return backend(notification_id, helper_app=helper_app, timeout=timeout)
    except Exception as exc:
        return {"ok": False, "mode": "error", "detail": str(exc)}


def mac_helper_app(name: str) -> Path:
    """macOS の通知ヘルパー `<name>.app` の既定のパス（存在するとは限らない）。

    ビルドは `just --justfile agent-compat/hooks/agent-tooling/justfile notify-helper-mac`。
    """
    return _mac_helper_app(name)


